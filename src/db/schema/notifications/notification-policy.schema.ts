import { sql } from 'drizzle-orm'
import { boolean, check, pgTable, text } from 'drizzle-orm/pg-core'
import { user } from '../auth/auth.schema'
import { createdAt, updatedAt, uuidv7PrimaryKey } from '../_shared/columns'
import { defaultJobNotificationRoles } from '#/features/notifications/notification-settings.schemas'
import type { Role } from '#/lib/authorization/permissions'

/** One company-wide notification policy. Missing initial configuration uses the enabled defaults. */
export const notificationPolicy = pgTable(
  'notification_policy',
  {
    /** Fixed singleton key; this single-company app has no tenant-specific policies. */
    id: text('id').primaryKey().default('company'),
    /** Selected roles receive every job event; an empty array disables job notifications without changing access. */
    jobNotificationRoles: text('job_notification_roles')
      .array()
      .$type<Array<Role>>()
      .notNull()
      .default(defaultJobNotificationRoles),
    /** UTC instant of the most recent policy write, maintained by Drizzle. */
    updatedAt: updatedAt(),
  },
  (table) => [
    check('notification_policy_singleton', sql`${table.id} = 'company'`),
  ],
)

/** Immutable history of real changes to the company notification policy, inserted in the same transaction. */
export const notificationPolicyAudit = pgTable('notification_policy_audit', {
  /** Time-ordered audit identity generated by PostgreSQL 18. */
  id: uuidv7PrimaryKey(),
  /** Trusted account that changed the policy; deletion cannot erase its audit identity. */
  actorId: text('actor_id')
    .notNull()
    .references(() => user.id, { onDelete: 'restrict' }),
  /** Historical creation-only switch before a legacy change; null for role-policy changes. */
  beforeEnabled: boolean('before_enabled'),
  /** Historical creation-only switch after a legacy change; null for role-policy changes. */
  afterEnabled: boolean('after_enabled'),
  /** Role selection before a current policy change; null for legacy creation-only audit entries. */
  beforeRoles: text('before_roles').array().$type<Array<Role>>(),
  /** Role selection after a current policy change; null for legacy creation-only audit entries. */
  afterRoles: text('after_roles').array().$type<Array<Role>>(),
  /** Database-generated UTC instant when the change was recorded. */
  createdAt: createdAt(),
})
